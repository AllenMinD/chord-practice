// Local study data from the downloadable MIDIdb demo. See README for provenance.
const fs = require("node:fs");
const path = require("node:path");
const { Midi } = require("@tonejs/midi");
const root = path.resolve(__dirname,"..");
const file = fs.readFileSync(path.join(root,"assets/reference/just-the-two-of-us-demo.mid"));
const midi = new Midi(file);
const track = midi.tracks.find(t => t.instrument.name === "tenor sax" && t.notes.length);
if(!track || midi.header.ppq !== 480) throw new Error("Unexpected reference MIDI layout");
const startTick = 3840, endTick = startTick + 32 * 480;
// Render sustained saxophone bend targets as playable piano pitches. The GM
// file has no RPN bend-range override; its default bend range is +/-2 semitones.
function pianoPitch(note) {
  let cursor = note.ticks;
  let value = track.pitchBends.filter(b => b.ticks <= cursor).at(-1)?.value || 0;
  const end = note.ticks + note.durationTicks, weights = new Map();
  for(const bend of [...track.pitchBends.filter(b => b.ticks > cursor && b.ticks < end),{ticks:end,value}]) {
    const semitones = Math.round(value*2);
    weights.set(semitones,(weights.get(semitones)||0) + bend.ticks-cursor);
    cursor = bend.ticks; value = bend.value;
  }
  return note.midi + [...weights].sort((a,b) => b[1]-a[1])[0][0];
}
const notes = track.notes.filter(n => n.ticks >= startTick-30 && n.ticks < endTick-30 && n.durationTicks >= 60)
  .map((n,i) => { const octaveShift = n.ticks >= startTick+16*480-30 ? 12 : 0; return { id:`melody-${i}`, start:Math.max(0,Math.round((n.ticks-startTick)/120)), duration:Math.max(1,Math.round(n.durationTicks/120)), midi:pianoPitch(n)+octaveShift, octaveShift, sourceMidi:n.midi, sourceTick:n.ticks, sourceDuration:n.durationTicks }; });
notes.forEach((n,i) => n.duration = Math.min(n.duration,(notes[i+1]?.start ?? 128)-n.start,128-n.start));
const data = {
  title:"Just the Two of Us · 萨克斯段钢琴练习", bpm:96, divisions:4, beats:32,
  source:{url:"https://www.mididb.com/grover-washington-jr/just-the-two-of-us-midi/",file:"AUD_AP4229MM.mid",sha256:require("node:crypto").createHash("sha256").update(file).digest("hex"),startTick,endTick,ppq:480,trackIndex:midi.tracks.indexOf(track),instrument:track.instrument.name},
  melody:notes
};
fs.writeFileSync(path.join(root,"just-two-data.js"),`// Generated by scripts/build-just-two-study.cjs. Local study only; do not publish.\n(function(root){ const data = ${JSON.stringify(data,null,2)}; if(typeof module!=="undefined"&&module.exports) module.exports=data; else root.JustTwoData=data; })(typeof globalThis!=="undefined"?globalThis:this);\n`);
console.log(`Prepared ${notes.length} melody notes across 8 measures from the reference saxophone track.`);
